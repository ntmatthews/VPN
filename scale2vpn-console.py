class ConsoleHandler(BaseHTTPRequestHandler):
    server_version = "Scale2VPN"

    def log_message(self, format_string, *args):
        logging.info("%s - %s", self.client_address[0], format_string % args)

    def send_bytes(self, status, content_type, data, extra_headers=None):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Content-Security-Policy", "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; base-uri 'none'; frame-ancestors 'none'")
        for key, value in (extra_headers or {}).items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(data)

    def send_html(self, status, title, body):
        data = page(title, body).encode("utf-8")
        self.send_bytes(status, "text/html; charset=utf-8", data)

    def authorized(self):
        authorization = self.headers.get("Authorization", "")
        if not authorization.startswith("Basic "):
            return False
        try:
            decoded = base64.b64decode(authorization[6:], validate=True).decode("utf-8")
            username, password = decoded.split(":", 1)
            expected_hash = PASSWORD_HASH_FILE.read_text(encoding="ascii").strip()
        except (ValueError, OSError, UnicodeDecodeError):
            return False
        actual_hash = hashlib.sha256(password.encode("utf-8")).hexdigest()
        return username == "admin" and hmac.compare_digest(actual_hash, expected_hash)

    def require_auth(self):
        if self.authorized():
            return True
        self.send_bytes(
            401,
            "text/plain; charset=utf-8",
            b"Authentication required\n",
            {"WWW-Authenticate": 'Basic realm="Scale2VPN Console", charset="UTF-8"'},
        )
        return False

    def require_same_origin(self):
        host = self.headers.get("Host", "")
        origin = self.headers.get("Origin", "")
        if not host or origin != f"https://{host}":
            self.send_html(403, "Request blocked", '<section class="card">Cross-origin requests are not accepted.</section>')
            return False
        return True

    def dashboard(self, notice=""):
        server = load_server()
        devices = read_devices()
        escaped_endpoint = html.escape(server["server_address"])
        escaped_remote_id = html.escape(server["remote_id"])
        routes = ", ".join(server["routes"])
        console_url = f"https://{server['server_address']}"
        if ":" in server["server_address"]:
            console_url = f"https://[{server['server_address']}]"
        body = f"""<p class="muted">Certificate-authenticated IKEv2 administration</p>
<section class="card">
<h2>Server</h2>
<div class="grid">
<div><span class="muted">Server Address</span><br><code>{escaped_endpoint}</code></div>
<div><span class="muted">Remote ID</span><br><code>{escaped_remote_id}</code></div>
<div><span class="muted">Tunnel routes</span><br><code>{html.escape(routes)}</code></div>
</div>
<p class="muted">Console: <a href="{html.escape(console_url)}:8443">{html.escape(console_url)}:8443</a></p>
</section>
<section class="card">
<h2>Add a device</h2>
<p class="muted">Each device gets a unique certificate identity and a one-time downloadable bundle.</p>
<form method="post" action="/devices">
<label for="display_name">Display Name</label>
<input id="display_name" name="display_name" maxlength="64" required autocomplete="off" placeholder="e.g. Alex's phone">
<p><button type="submit">Create device profile</button></p>
</form>
</section>
<section class="card">
<h2>Certificate trust chain</h2>
<div class="grid">
<div><strong>CA / Root</strong><br><code>Scale2VPN Root CA</code></div>
<div><strong>MID / Intermediate</strong><br><code>Scale2VPN Intermediate CA</code></div>
<div><strong>Device / Leaf</strong><br><code>Unique per-device certificate</code></div>
</div>
<p class="muted">The device certificate is signed by the intermediate; the intermediate is signed by the root CA. The full chain is included in each device bundle.</p>
</section>"""
        if notice:
            body += f'<div class="notice">{html.escape(notice)}</div>'
        body += "<section class=\"card\"><h2>Devices</h2>"
        if not devices:
            body += '<p class="muted">No devices have been issued yet.</p>'
        else:
            body += "<table><thead><tr><th>Display Name</th><th>Local ID</th><th>Created</th><th></th></tr></thead><tbody>"
            for device_id, device in sorted(devices.items(), key=lambda item: item[1]["created"]):
                body += (
                    "<tr>"
                    f"<td>{html.escape(device['display_name'])}</td>"
                    f"<td><code>{html.escape(device['local_id'])}</code></td>"
                    f"<td>{html.escape(device['created'])}</td>"
                    "<td><form class=\"inline\" method=\"post\" action=\"/revoke\">"
                    f"<input type=\"hidden\" name=\"device_id\" value=\"{html.escape(device_id)}\">"
                    '<button class="danger" type="submit">Revoke</button></form></td>'
                    "</tr>"
                )
            body += "</tbody></table>"
        body += "</section>"
        self.send_html(200, "Console", body)

    def do_GET(self):
        if not self.require_auth():
            return
        purge_pending_downloads()
        parsed = urlparse(self.path)
        if parsed.path == "/":
            self.dashboard()
            return
        if parsed.path.startswith("/download/"):
            token = parsed.path.removeprefix("/download/")
            entry = PENDING_DOWNLOADS.get(token)
            if not entry or entry["expires"] < time.monotonic():
                PENDING_DOWNLOADS.pop(token, None)
                self.send_html(404, "Profile expired", '<section class="card">This one-time download expired. Create a new device profile.</section>')
                return
            PENDING_DOWNLOADS.pop(token, None)
            self.send_bytes(
                200,
                "application/zip",
                entry["bundle"],
                {"Content-Disposition": f'attachment; filename="{entry["filename"]}"'},
            )
            return
        self.send_html(404, "Not found", '<section class="card">Page not found.</section>')

    def read_form(self):
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            raise ValueError("Invalid form length.")
        if length < 1 or length > 8192:
            raise ValueError("Form is empty or too large.")
        values = parse_qs(self.rfile.read(length).decode("utf-8"), keep_blank_values=True)
        return {key: items[0] for key, items in values.items()}

    def do_POST(self):
        if not self.require_auth() or not self.require_same_origin():
            return
        purge_pending_downloads()
        try:
            form = self.read_form()
            route = urlparse(self.path).path
            if route == "/devices":
                display_name = validate_display_name(form.get("display_name", ""))
                device_id, device, token = issue_device(display_name)
                body = f"""<section class="card">
<h2>Device profile created</h2>
<p><strong>Display Name:</strong> {html.escape(device['display_name'])}</p>
<p><strong>Server Address:</strong> <code>{html.escape(load_server()['server_address'])}</code></p>
<p><strong>Remote ID:</strong> <code>{html.escape(load_server()['remote_id'])}</code></p>
<p><strong>Local ID:</strong> <code>{html.escape(device['local_id'])}</code></p>
<p><strong>Authentication:</strong> IKEv2 certificate (PKCS#12)</p>
<p><strong>CA → MID → device certificate:</strong> included in the bundle and trusted by the server.</p>
<div class="notice">PKCS#12 import password (shown once): <code>{html.escape(PENDING_DOWNLOADS[token]['password'])}</code></div>
<p><a class="button" href="/download/{html.escape(token)}">Download device bundle</a></p>
<p><a href="/">Return to console</a></p>
</section>"""
                self.send_html(201, "Device profile", body)
                return
            if route == "/revoke":
                revoke_device(form.get("device_id", ""))
                self.dashboard("Device revoked. New IKEv2 connections with its local ID are no longer accepted.")
                return
            self.send_html(404, "Not found", '<section class="card">Page not found.</section>')
        except ValueError as error:
            self.send_html(400, "Invalid request", f'<section class="card">{html.escape(str(error))}</section>')
        except Exception:
            logging.exception("Scale2VPN console request failed")
            self.send_html(500, "Operation failed", '<section class="card">The operation failed. Check <code>journalctl -u scale2vpn-console</code>.</section>')


def main():
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    RUNTIME_DIR.mkdir(mode=0o700, parents=True, exist_ok=True)
    server_config = load_server()
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.minimum_version = ssl.TLSVersion.TLSv1_2
    context.load_cert_chain(certfile=SERVER_CERT, keyfile=SERVER_KEY)

    servers = []
    if "ipv4" in server_config["families"]:
        ipv4_server = ThreadingHTTPServer(("0.0.0.0", 8443), ConsoleHandler)
        ipv4_server.socket = context.wrap_socket(ipv4_server.socket, server_side=True)
        servers.append(ipv4_server)
    if "ipv6" in server_config["families"]:
        class IPv6HTTPServer(ThreadingHTTPServer):
            address_family = socket.AF_INET6

            def server_bind(self):
                self.socket.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
                super().server_bind()

        ipv6_server = IPv6HTTPServer(("::", 8443), ConsoleHandler)
        ipv6_server.socket = context.wrap_socket(ipv6_server.socket, server_side=True)
        servers.append(ipv6_server)

    if not servers:
        raise RuntimeError("No public IP family is configured for the console")
    for server in servers[1:]:
        threading.Thread(target=server.serve_forever, daemon=True).start()
    logging.info("Scale2VPN public HTTPS console listening on port 8443")
    servers[0].serve_forever()


if __name__ == "__main__":
    main()
