CONFIG_DIR = Path("/etc/scale2vpn")
CA_DIR = CONFIG_DIR / "ca"
DEVICES_DIR = CONFIG_DIR / "devices"
SERVER_FILE = CONFIG_DIR / "server.json"
DEVICES_FILE = CONFIG_DIR / "devices.json"
DEVICES_CONFIG = Path("/etc/ipsec.d/scale2vpn_devices.conf")
CERT_DIR = Path("/etc/ipsec.d/certs")
SERVER_CERT = CERT_DIR / "scale2vpn-console-chain.pem"
SERVER_KEY = Path("/etc/ipsec.d/private/scale2vpn-server-key.pem")
RUNTIME_DIR = Path("/run/scale2vpn")
PASSWORD_HASH_FILE = CONFIG_DIR / "console-password.sha256"
DEVICE_ID_PATTERN = re.compile(r"^[0-9a-f]{24}$")
PENDING_DOWNLOADS = {}
DOWNLOAD_TTL = 600


def run_tool(args, *, input_data=None, timeout=60):
    result = subprocess.run(
        args,
        input=input_data,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
        timeout=timeout,
    )
    if result.returncode:
        detail = result.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(f"{Path(args[0]).name} failed: {detail}")
    return result.stdout


def atomic_write(path, data, mode=0o600):
    path = Path(path)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        os.fchmod(fd, mode)
        with os.fdopen(fd, "wb") as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def read_devices():
    with DEVICES_FILE.open(encoding="utf-8") as source:
        devices = json.load(source)
    if not isinstance(devices, dict):
        raise RuntimeError("The device database is invalid")
    return devices


def serialize_devices(devices):
    return (json.dumps(devices, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def render_devices_config(devices):
    lines = ["# Generated by the Scale2VPN console; do not edit."]
    for device_id, device in sorted(devices.items()):
        if not DEVICE_ID_PATTERN.fullmatch(device_id):
            raise RuntimeError("Invalid device ID in database")
        local_id = device["local_id"]
        if not re.fullmatch(r"s2v-[0-9a-f]{12}", local_id):
            raise RuntimeError("Invalid device identity in database")
        lines.extend(
            [
                "",
                f"conn scale2vpn-device-{device_id}",
                "    also=scale2vpn-ikev2-device-template",
                "    auto=add",
                f"    rightid=@{local_id}",
            ]
        )
    return ("\n".join(lines) + "\n").encode("utf-8")


def validate_display_name(value):
    name = value.strip()
    if not name or len(name) > 64 or any(ord(char) < 32 or ord(char) == 127 for char in name):
        raise ValueError("Display Name must be 1-64 printable characters.")
    return name


def load_server():
    with SERVER_FILE.open(encoding="utf-8") as source:
        return json.load(source)


def purge_pending_downloads():
    current_time = time.monotonic()
    for token in [key for key, value in PENDING_DOWNLOADS.items() if value["expires"] < current_time]:
        PENDING_DOWNLOADS.pop(token, None)


def issue_device(display_name):
    server = load_server()
    device_id = secrets.token_hex(12)
    local_id = f"s2v-{secrets.token_hex(6)}"
    device = {
        "display_name": display_name,
        "local_id": local_id,
        "created": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
    }

    with tempfile.TemporaryDirectory(prefix="device-", dir=RUNTIME_DIR) as temporary_dir:
        temporary = Path(temporary_dir)
        private_key = temporary / "device-key.pem"
        certificate = temporary / "device-cert.pem"
        private_key_data = run_tool(["pki", "--gen", "--type", "rsa", "--size", "3072", "--outform", "pem"])
        atomic_write(private_key, private_key_data, 0o600)
        public_part = run_tool(["pki", "--pub", "--in", str(private_key)])
        certificate_data = run_tool(
            [
                "pki",
                "--issue",
                "--cacert",
                str(CA_DIR / "intermediate-cert.pem"),
                "--cakey",
                str(CA_DIR / "intermediate-key.pem"),
                "--dn",
                f"CN={local_id}",
                "--san",
                local_id,
                "--flag",
                "clientAuth",
                "--lifetime",
                "1825",
                "--outform",
                "pem",
            ],
            input_data=public_part,
        )
        atomic_write(certificate, certificate_data, 0o600)

        chain_file = temporary / "ca-chain.pem"
        chain_file.write_bytes(
            (CA_DIR / "intermediate-cert.pem").read_bytes()
            + (CA_DIR / "root-cert.pem").read_bytes()
        )
        p12_password = secrets.token_urlsafe(18)
        p12_file = temporary / "device.p12"
        run_tool(
            [
                "openssl",
                "pkcs12",
                "-export",
                "-out",
                str(p12_file),
                "-inkey",
                str(private_key),
                "-in",
                str(certificate),
                "-certfile",
                str(chain_file),
                "-name",
                display_name,
                "-passout",
                f"pass:{p12_password}",
            ]
        )

        profile = (
            f"Display Name: {display_name}\n"
            f"Server Address: {server['server_address']}\n"
            f"Remote ID: {server['remote_id']}\n"
            f"Local ID: {local_id}\n"
            "Authentication: IKEv2 certificate authentication\n"
            "CA certificate (root): root-ca.pem\n"
            "MID certificate (intermediate): intermediate-ca.pem\n"
            "Device certificate (leaf): device-cert.pem\n"
            "Identity package: device.p12\n"
            "Import password: shown once in the Scale2VPN console\n"
            "Trust chain: device certificate -> intermediate CA -> root CA\n"
            f"Tunnel routes: {', '.join(server['routes'])}\n"
        )
        bundle_buffer = io.BytesIO()
        with zipfile.ZipFile(bundle_buffer, "w", zipfile.ZIP_DEFLATED) as bundle:
            bundle.writestr("profile.txt", profile)
            bundle.write(p12_file, "device.p12")
            bundle.write(certificate, "device-cert.pem")
            bundle.write(CA_DIR / "intermediate-cert.pem", "intermediate-ca.pem")
            bundle.write(CA_DIR / "root-cert.pem", "root-ca.pem")
        bundle_data = bundle_buffer.getvalue()

    cert_path = DEVICES_DIR / f"{device_id}.pem"
    atomic_write(cert_path, certificate_data, 0o644)
    devices = read_devices()
    devices[device_id] = device
    old_database = DEVICES_FILE.read_bytes()
    old_connections = DEVICES_CONFIG.read_bytes()
    try:
        atomic_write(DEVICES_FILE, serialize_devices(devices))
        atomic_write(DEVICES_CONFIG, render_devices_config(devices), 0o600)
        run_tool(["ipsec", "reload"])
    except Exception:
        atomic_write(DEVICES_FILE, old_database)
        atomic_write(DEVICES_CONFIG, old_connections, 0o600)
        cert_path.unlink(missing_ok=True)
        try:
            run_tool(["ipsec", "reload"])
        except Exception:
            logging.exception("Could not reload the previous strongSwan configuration")
        raise

    token = secrets.token_urlsafe(24)
    purge_pending_downloads()
    PENDING_DOWNLOADS[token] = {
        "expires": time.monotonic() + DOWNLOAD_TTL,
        "bundle": bundle_data,
        "password": p12_password,
        "filename": f"Scale2VPN-{device_id}.zip",
    }
    return device_id, device, token


def revoke_device(device_id):
    if not DEVICE_ID_PATTERN.fullmatch(device_id):
        raise ValueError("Invalid device ID.")
    devices = read_devices()
    device = devices.get(device_id)
    if device is None:
        raise ValueError("Device not found.")
    try:
        run_tool(["ipsec", "down", f"scale2vpn-device-{device_id}"])
    except RuntimeError:
        logging.warning("No active IKE_SA was disconnected for device %s", device_id)

    updated = dict(devices)
    del updated[device_id]
    certificate_path = DEVICES_DIR / f"{device_id}.pem"
    old_database = DEVICES_FILE.read_bytes()
    old_connections = DEVICES_CONFIG.read_bytes()
    try:
        atomic_write(DEVICES_FILE, serialize_devices(updated))
        atomic_write(DEVICES_CONFIG, render_devices_config(updated), 0o600)
        run_tool(["ipsec", "reload"])
    except Exception:
        atomic_write(DEVICES_FILE, old_database)
        atomic_write(DEVICES_CONFIG, old_connections, 0o600)
        try:
            run_tool(["ipsec", "reload"])
        except Exception:
            logging.exception("Could not reload the previous strongSwan configuration")
        raise
    certificate_path.unlink(missing_ok=True)
    return device


